import type { FileNode } from "@/lib/types";

/**
 * Nestable file manifests for the inspector's "Includes" view, rendered as a
 * `tree` / VS-Code-style collapsible file tree. Names are what the generated
 * project actually ships (the CLI's `_gitignore` -> `.gitignore` rename
 * applied), so this mirrors `packages/create-chaos/templates`.
 *
 * `includes` in `template-details.ts` stays the flat documentation copy; this
 * file is the richer interactive view. A folder lists its `children` when we
 * want it expandable and always carries `count` (its immediate children), so
 * a collapsed folder shows a "N" badge like VS Code does.
 */

const F = (name: string): FileNode => ({ name, type: "file" });
const D = (name: string, count?: number, children?: FileNode[]): FileNode => ({
  name,
  type: "folder",
  count,
  children,
});

